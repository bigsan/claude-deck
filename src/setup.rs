//! `claude-deck setup`: register the deck with herdr, and the permission-verdict hook
//! with Claude Code.
//!
//! herdr: a plugin folder is written whose manifest runs this binary by its absolute
//! path (herdr runs manifest commands without a shell), then linked with
//! `herdr plugin link`. Run it again after moving the binary. A plugin installed from
//! GitHub (`herdr plugin install`) is left alone: it runs its own release binary.
//!
//! hooks: the session-deck-hooks Claude Code plugin (claude-plugin/ in the source tree,
//! carried inside the binary) is written out as a local marketplace and installed with
//! `claude plugin`. It writes gate.jsonl, from which the deck tells who allowed a call.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use crate::data::home;
use crate::herdr::PLUGIN_ID;

const HOOKS_JSON: &str = include_str!("../claude-plugin/hooks/hooks.json");
const GATE_LOG: &str = include_str!("../claude-plugin/hooks/gate-log.py");
const HOOKS_PLUGIN: &str = include_str!("../claude-plugin/.claude-plugin/plugin.json");
const MARKETPLACE: &str = "claude-deck-hooks";
const HOOKS_NAME: &str = "session-deck-hooks";

const CONFIG_HEADER: &str = "# Claude Deck configuration, for the herdr plugin and standalone alike:
#   cp config.example.env \"$(herdr plugin config-dir bigsan.claude-deck)/config.env\"
# Every key can also be set as an environment variable with a DECK_ prefix,
# e.g. DECK_LOG_LEVEL=debug.
";

fn data_home() -> PathBuf {
    std::env::var_os("XDG_DATA_HOME").map(PathBuf::from).filter(|p| p.is_absolute()).unwrap_or_else(|| home().join(".local/share"))
}

fn plugin_dir() -> PathBuf {
    crate::config::config_home().join("herdr/claude-deck-plugin")
}

fn exe() -> Result<PathBuf, String> {
    let exe = std::env::current_exe().map_err(|e| format!("cannot find this binary: {e}"))?;
    Ok(fs::canonicalize(&exe).unwrap_or(exe))
}

/// A TOML basic string (JSON's escaping is valid TOML).
fn quoted(text: &str) -> String {
    serde_json::to_string(text).unwrap_or_default()
}

/// How herdr-plugin.toml in the source tree runs the binary: through bin/claude-deck.sh,
/// by $HERDR_PLUGIN_ROOT since the deck pane opens in the session directory. Only the
/// tests use it: they check the checked-in file against it, and rewrite it on request.
#[cfg(test)]
const REPO_RUN: &[&str] = &["sh", "-c", "exec sh \"$HERDR_PLUGIN_ROOT/bin/claude-deck.sh\" \"$@\"", "claude-deck"];

/// The manifest `setup herdr` writes: runs this binary by its absolute path.
fn manifest(exe: &Path) -> String {
    manifest_with(
        "# Generated by `claude-deck setup herdr`; run it again after moving the binary.\n",
        &[&exe.to_string_lossy()],
        "",
    )
}

/// herdr-plugin.toml in the source tree, for `herdr plugin install bigsan/claude-deck`.
#[cfg(test)]
fn repo_manifest() -> String {
    manifest_with(
        "# For `herdr plugin install bigsan/claude-deck`: the build step downloads this version's\n\
         # release binary (scripts/fetch-release.sh). Generated from src/setup.rs; cargo test\n\
         # checks it is current, and UPDATE_MANIFEST=1 cargo test rewrites it.\n",
        REPO_RUN,
        "[[build]]\ncommand = [\"sh\", \"scripts/fetch-release.sh\"]\n\n",
    )
}

/// A manifest whose commands are `run` followed by claude-deck's arguments.
fn manifest_with(header: &str, run: &[&str], build: &str) -> String {
    let command = |args: &[&str]| format!("[{}]", run.iter().chain(args).map(|a| quoted(a)).collect::<Vec<_>>().join(", "));
    let action = |id: &str, title: &str, description: &str| {
        format!(
            "[[actions]]\nid = \"{id}\"\ntitle = \"{title}\"\ndescription = \"{description}\"\ncontexts = [\"pane\", \"workspace\"]\ncommand = {}\n",
            command(&["herdr", id])
        )
    };
    let mut out = format!(
        "{header}#\n\
         # Docks a Claude Code session beside its agent pane: the scratchpad's files as they\n\
         # change, tasks/ (background shells and subagents), and every tool call with its\n\
         # time, command, exit code and output, in three views (A tabs, B columns, C timeline).\n\
         # The sessions action lists every running session.\n\n\
         id = \"{PLUGIN_ID}\"\nname = \"Claude Deck\"\nversion = \"{}\"\nmin_herdr_version = \"0.9.0\"\n\
         description = \"A Claude Code session's scratchpad, tasks and tool calls beside it, and every running session in one list.\"\n\
         platforms = [\"macos\", \"linux\"]\n\n\
         {build}\
         [[panes]]\nid = \"deck\"\ntitle = \"Claude Deck\"\nplacement = \"split\"\ncommand = {}\n\n\
         [[panes]]\nid = \"sessions\"\ntitle = \"Claude sessions\"\nplacement = \"split\"\ncommand = {}\n\n\
         [[events]]\non = \"pane.agent_status_changed\"\ncommand = {}\n\n\
         [[events]]\non = \"pane.closed\"\ncommand = {}\n\n",
        env!("CARGO_PKG_VERSION"),
        command(&[]),
        command(&[]),
        command(&["herdr", "event"]),
        command(&["herdr", "event"]),
    );
    for (id, title, description) in [
        ("toggle", "Claude deck: toggle", "Open the focused Claude session's deck beside it, or close it."),
        ("open-a", "Claude deck: open in tabs view (A)", "Open the deck in view A: Files / Tasks / Calls tabs with a preview."),
        ("open-b", "Claude deck: open in columns view (B)", "Open the deck in view B: sources, list and a live detail column."),
        ("open-c", "Claude deck: open in timeline view (C)", "Open the deck in view C: one stream of file changes, tasks and calls."),
        ("close", "Claude deck: close", "Close the deck for the focused agent pane."),
        ("sessions", "Claude deck: all sessions", "Open every running Claude Code session in one list beside the focused pane."),
        ("path", "Claude deck: print paths", "Print the session directory and transcript the deck would show."),
        ("reveal", "Claude deck: reveal folder", "Open the session directory in the file manager."),
    ] {
        out.push_str(&action(id, title, description));
        out.push('\n');
    }
    out
}

/// Where herdr has `PLUGIN_ID` from, per `herdr plugin list --json`.
#[derive(Debug, PartialEq)]
enum Installed {
    None,
    /// `herdr plugin link`ed from this folder.
    Local(String),
    /// `herdr plugin install`ed from GitHub at this commit.
    GitHub { owner: String, repo: String, commit: String },
    /// A source kind this binary does not know.
    Other(String),
}

fn installed() -> Installed {
    match Command::new("herdr").args(["plugin", "list", "--json", "--plugin", PLUGIN_ID]).output() {
        Ok(out) if out.status.success() => parse_installed(&String::from_utf8_lossy(&out.stdout)),
        _ => Installed::None,
    }
}

fn parse_installed(json: &str) -> Installed {
    let Ok(value) = serde_json::from_str::<serde_json::Value>(json) else { return Installed::None };
    let Some(plugin) = value["result"]["plugins"].as_array().and_then(|plugins| {
        plugins.iter().find(|p| p["plugin_id"].as_str() == Some(PLUGIN_ID))
    }) else {
        return Installed::None;
    };
    let text = |v: &serde_json::Value| v.as_str().unwrap_or_default().to_string();
    let source = &plugin["source"];
    match source["kind"].as_str().unwrap_or_default() {
        "local" => Installed::Local(text(&plugin["plugin_root"])),
        "github" => Installed::GitHub {
            owner: text(&source["owner"]),
            repo: text(&source["repo"]),
            commit: text(&source["resolved_commit"]),
        },
        kind => Installed::Other(kind.to_string()),
    }
}

fn setup_herdr(check: bool) -> Result<String, String> {
    let exe = exe()?;
    let dir = plugin_dir();
    let wanted = manifest(&exe);
    let current = fs::read_to_string(dir.join("herdr-plugin.toml")).unwrap_or_default();
    let installed = installed();
    // A GitHub install runs its own release binary and follows releases with
    // `herdr plugin update`; linking over it would need an uninstall, so leave it be.
    if let Installed::GitHub { owner, repo, commit } = &installed {
        let short = &commit[..commit.len().min(7)];
        let from = format!("installed from GitHub {owner}/{repo}@{short}");
        return Ok(if check {
            from
        } else {
            format!("{from}\nherdr plugin update {PLUGIN_ID} follows new releases; to run this binary instead, herdr plugin uninstall {PLUGIN_ID} and run claude-deck setup herdr again")
        });
    }
    if let Installed::Other(kind) = &installed {
        return Err(format!("{PLUGIN_ID} is installed from an unknown source ({kind}); remove it with herdr before claude-deck setup herdr"));
    }
    let linked = match installed {
        Installed::Local(path) => Some(path),
        _ => None,
    };
    let here = linked.as_deref() == Some(&*dir.to_string_lossy());
    if check {
        return match (here, current == wanted) {
            (true, true) => Ok(format!("linked: {PLUGIN_ID} from {} runs {}", dir.display(), exe.display())),
            (true, false) => Err(format!("stale: {} does not run {}; run claude-deck setup herdr", dir.display(), exe.display())),
            (false, _) => Err(format!("unlinked: {PLUGIN_ID} is not linked{}", linked.map(|p| format!(" (linked from {p})")).unwrap_or_default())),
        };
    }
    fs::create_dir_all(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    fs::write(dir.join("herdr-plugin.toml"), &wanted).map_err(|e| format!("{}: {e}", dir.display()))?;
    fs::write(dir.join("config.example.env"), crate::config::example(CONFIG_HEADER)).map_err(|e| format!("{}: {e}", dir.display()))?;
    let mut done = vec![format!("wrote {}", dir.join("herdr-plugin.toml").display())];
    if !here {
        if linked.is_some() {
            run("herdr", &["plugin", "unlink", PLUGIN_ID])?;
        }
        run("herdr", &["plugin", "link", &dir.to_string_lossy()])?;
        done.push(format!("linked {PLUGIN_ID}"));
    }
    done.push(format!("the pane runs {}", exe.display()));
    Ok(done.join("\n"))
}

fn run(program: &str, args: &[&str]) -> Result<String, String> {
    let out = Command::new(program).args(args).output().map_err(|e| format!("{program}: {e}"))?;
    if !out.status.success() {
        return Err(format!("{program} {}: {}", args.join(" "), String::from_utf8_lossy(&out.stderr).trim()));
    }
    Ok(String::from_utf8_lossy(&out.stdout).into_owned())
}

/// The marketplace a session-deck-hooks plugin is enabled from, if any.
fn hooks_enabled() -> Option<String> {
    let settings = fs::read(crate::data::claude_config_dir().join("settings.json")).ok()?;
    let settings: serde_json::Value = serde_json::from_slice(&settings).ok()?;
    settings["enabledPlugins"].as_object()?.iter().find_map(|(key, on)| {
        let (name, market) = key.split_once('@')?;
        (name == HOOKS_NAME && on.as_bool() == Some(true)).then(|| market.to_string())
    })
}

fn setup_hooks(check: bool) -> Result<String, String> {
    if let Some(market) = hooks_enabled() {
        return Ok(format!("installed: {HOOKS_NAME}@{market} is enabled; gate.jsonl is written"));
    }
    if check {
        return Err(format!("not installed: run claude-deck setup hooks to install {HOOKS_NAME}"));
    }
    let root = data_home().join("claude-deck/marketplace");
    let plugin = root.join("claude-plugin");
    let write = |path: PathBuf, text: &str| -> Result<(), String> {
        fs::create_dir_all(path.parent().unwrap_or(&root)).map_err(|e| format!("{}: {e}", path.display()))?;
        fs::write(&path, text).map_err(|e| format!("{}: {e}", path.display()))
    };
    let catalog = serde_json::json!({
        "name": MARKETPLACE,
        "owner": { "name": "claude-deck" },
        "plugins": [{ "name": HOOKS_NAME, "source": "./claude-plugin", "description": "Permission-verdict log for Claude Deck" }],
    });
    write(root.join(".claude-plugin/marketplace.json"), &serde_json::to_string_pretty(&catalog).unwrap_or_default())?;
    write(plugin.join(".claude-plugin/plugin.json"), HOOKS_PLUGIN)?;
    write(plugin.join("hooks/hooks.json"), HOOKS_JSON)?;
    write(plugin.join("hooks/gate-log.py"), GATE_LOG)?;
    run("claude", &["plugin", "marketplace", "add", &root.to_string_lossy()])?;
    run("claude", &["plugin", "install", &format!("{HOOKS_NAME}@{MARKETPLACE}")])?;
    Ok(format!("installed {HOOKS_NAME}@{MARKETPLACE} from {}\nnew Claude Code sessions write gate.jsonl", root.display()))
}

/// `claude-deck setup <herdr|hooks> [--check]`: the exit code.
pub fn main(args: &[String]) -> i32 {
    let check = args.iter().any(|a| a == "--check");
    let result = match args.first().map(String::as_str) {
        Some("herdr") => setup_herdr(check),
        Some("hooks") => setup_hooks(check),
        _ => {
            eprintln!("usage: claude-deck setup <herdr|hooks> [--check]");
            return 2;
        }
    };
    match result {
        Ok(message) => {
            println!("{message}");
            0
        }
        Err(message) => {
            eprintln!("claude-deck: {message}");
            1
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;


    #[test]
    fn a_github_install_is_read_from_its_source() {
        let json = r#"{"id":"cli:plugin","result":{"plugins":[{"plugin_id":"bigsan.claude-deck","plugin_root":"/h/checkout",
            "source":{"kind":"github","owner":"bigsan","repo":"claude-deck","resolved_commit":"1dea3ccfbbe9e77a49ae32f295e26d247609e8e9","managed_path":"/h/checkout"}}],"type":"plugin_list"}}"#;
        assert_eq!(
            parse_installed(json),
            Installed::GitHub { owner: "bigsan".into(), repo: "claude-deck".into(), commit: "1dea3ccfbbe9e77a49ae32f295e26d247609e8e9".into() }
        );
    }

    #[test]
    fn a_link_is_read_from_its_plugin_root() {
        let json = r#"{"id":"cli:plugin","result":{"plugins":[{"plugin_id":"bigsan.claude-deck","plugin_root":"/home/u/.config/herdr/claude-deck-plugin",
            "source":{"kind":"local"}}],"type":"plugin_list"}}"#;
        assert_eq!(parse_installed(json), Installed::Local("/home/u/.config/herdr/claude-deck-plugin".into()));
    }

    #[test]
    fn no_plugin_or_no_herdr_output_is_not_installed() {
        assert_eq!(parse_installed(r#"{"id":"cli:plugin","result":{"plugins":[],"type":"plugin_list"}}"#), Installed::None);
        assert_eq!(parse_installed(""), Installed::None);
        let other = r#"{"result":{"plugins":[{"plugin_id":"herdr-tsk","source":{"kind":"local"}}]}}"#;
        assert_eq!(parse_installed(other), Installed::None);
    }
    #[test]
    fn the_manifest_runs_the_binary_by_absolute_path() {
        let text = manifest(Path::new("/opt/bin/claude deck"));
        assert!(text.contains("id = \"bigsan.claude-deck\""));
        assert!(text.contains("command = [\"/opt/bin/claude deck\"]"));
        assert!(text.contains("command = [\"/opt/bin/claude deck\", \"herdr\", \"toggle\"]"));
        assert_eq!(text.matches("[[actions]]").count(), 8);
    }

    #[test]
    fn the_repo_manifest_is_current() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("herdr-plugin.toml");
        if std::env::var_os("UPDATE_MANIFEST").is_some() {
            fs::write(&path, repo_manifest()).unwrap();
        }
        let text = fs::read_to_string(&path).unwrap_or_default();
        assert!(text == repo_manifest(), "herdr-plugin.toml is out of date: run UPDATE_MANIFEST=1 cargo test");
        assert!(text.contains(&format!("version = \"{}\"", env!("CARGO_PKG_VERSION"))));
        assert!(text.contains("command = [\"sh\", \"scripts/fetch-release.sh\"]"));
    }

    /// config.example.env in the source tree, so a `herdr plugin install` has it in its
    /// plugin folder the way `setup herdr` writes it beside its manifest.
    #[test]
    fn the_repo_example_config_is_current() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("config.example.env");
        let wanted = crate::config::example(CONFIG_HEADER);
        if std::env::var_os("UPDATE_MANIFEST").is_some() {
            fs::write(&path, &wanted).unwrap();
        }
        let text = fs::read_to_string(&path).unwrap_or_default();
        assert!(text == wanted, "config.example.env is out of date: run UPDATE_MANIFEST=1 cargo test");
    }
}
